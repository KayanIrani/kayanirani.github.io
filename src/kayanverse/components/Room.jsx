import React, { useEffect, useRef, useState } from 'react'
import { useGLTF } from '@react-three/drei'
import {Color} from "three"

import { convertMaterialsToMeshBasicMaterial } from '../../utils/convertMaterial'
import { useFrame } from '@react-three/fiber'

import LaptopScreenView from '../../components/LaptopScreenView'
import HtmlOverlay from '../elements/HtmlOverlay/HtmlOverlay'
import Glass from '../elements/Glass'
import { Book } from '../elements/Diary/Book'


export default function Model({progress=0,...props}) {

  const { nodes, materials } = useGLTF('/models/withDiary-transformed.glb')
  // convertMaterialsToMeshBasicMaterial(materials)
  // console.log(nodes)
  // console.log(materials);

  let lerpFactor = 0
  const laptopScreenConfigs = {
    openingProgress: 0.40,
    closingProgress: 0.95,
    initalAngle: Math.PI/2,
    // initalAngle: 3*Math.PI/2,
    // finalAngle: Math.PI - Math.PI/10
    finalAngle: -Math.PI/10
  }

  const laptopScreenRef= useRef()
  const htmlLaptopScreen= useRef()
  const laptopScreenPosition = [0,10.5,0]
  const laptopScreenRotation = [0, 0, 0]


  const [isHidden, setHidden] = useState(false)


  useEffect(()=>{
    if (progress>=0.86){
      htmlLaptopScreen.current.rotation.x = laptopScreenConfigs.finalAngle 
      htmlLaptopScreen.current.visible = true
      setHidden(false)
    }
    else{
      htmlLaptopScreen.current.visible = false
      // htmlLaptopScreen.current.rotation.x = laptopScreenConfigs.initalAngle
      // console.log(htmlLaptopScreen)
      setHidden(true)

    }
    if (progress>=laptopScreenConfigs.openingProgress && progress<=laptopScreenConfigs.closingProgress){
      lerpFactor = (progress-laptopScreenConfigs.openingProgress) / (laptopScreenConfigs.closingProgress-laptopScreenConfigs.openingProgress)
      laptopScreenRef.current.rotation.x = laptopScreenConfigs.initalAngle + ((laptopScreenConfigs.finalAngle -laptopScreenConfigs.initalAngle) * lerpFactor)


    }
    else if (progress>laptopScreenConfigs.closingProgress){
      laptopScreenRef.current.rotation.x = laptopScreenConfigs.finalAngle
    }
    else{
      laptopScreenRef.current.rotation.x = laptopScreenConfigs.initalAngle
    }
  },[progress])
  return ( 
    <group {...props} dispose={null}>
      <group name="Scene">
        <mesh name="Desk" geometry={nodes.Desk.geometry} material={materials['Material.001']} />
        <mesh name="Mousepad" geometry={nodes.Mousepad.geometry} material={materials.MousepadMaterial} />
        <group name="Mouse">
          <mesh name="Mouse_1" geometry={nodes.Mouse_1.geometry} material={materials.MouseScroller} />
          <mesh name="Mouse_2" geometry={nodes.Mouse_2.geometry} material={materials.MouseColor} />
        </group>
        <mesh name="Phone" geometry={nodes.Phone.geometry} material={materials.PhoneCover} />
        <mesh name="PhoneScreen" geometry={nodes.PhoneScreen.geometry} material={materials.Screen} />
        <mesh name="PhoneCamera" geometry={nodes.PhoneCamera.geometry} material={materials.Material} />
        <mesh name="USBPortInner" geometry={nodes.USBPortInner.geometry} material={materials.Metal} />
        <mesh name="Room" geometry={nodes.Room.geometry} material={materials.Walls} />
        <mesh name="RoomFloor" geometry={nodes.RoomFloor.geometry} material={materials.Floor} />
        <group name="Window">
          <mesh name="Window_1" geometry={nodes.Window_1.geometry} material={materials.Window} />
          <mesh name="Window_2" geometry={nodes.Window_2.geometry} material={materials.insulationMaterial} />
        </group>
        <mesh name="GlassPane" geometry={nodes.GlassPane.geometry}>
          <Glass />
        </mesh>
        <mesh name="Frame_ComputerFrame_0" geometry={nodes.Frame_ComputerFrame_0.geometry} material={materials.ComputerFrame} />
        <mesh name="Screen_ComputerScreen_0" geometry={nodes.Screen_ComputerScreen_0.geometry} material={materials.ComputerScreen} ref={laptopScreenRef} position={[0, 0.429, -10.092]}  />
        <mesh name="ComputerScreenHTML" geometry={nodes.Screen_ComputerScreen_0.geometry} ref={htmlLaptopScreen} position={[0, 0.429, -10.092]} >
          <HtmlOverlay  
            isHidden={isHidden} setHidden={setHidden} position={laptopScreenPosition} rotation={laptopScreenRotation}
          />
        </mesh>
       <group name="DiaryAnchor" position={[30.596, 1.2, -2]} rotation-y={-Math.PI/5} >
          <Book scale={8}/>
       </group>
      </group>
    </group>
  )
}

